"""Generate deterministic structural INT8 weights + golden vectors.

The weights are NOT trained: this project is the FPGA-side deliverable and the
semantic checkpoint (normal/fall/other) is supplied separately.  Everything here
is deterministic (fixed seed) so RTL and Python stay bit-exact and every artefact
can be regenerated and SHA256-checked.

Layout (documented in docs/QUANT_SPEC.md):
  conv weight index = (oc*IC + ic)*9 + (kh*3 + kw)
  fc   weight index = oc*32 + k
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

from int_reference import CLASS_ORDER, infer, write_hex

ROOT = Path(__file__).resolve().parents[1]
W = ROOT / "weights"
G = ROOT / "sim" / "golden"

SEED = 20261030
# per layer: (in_scale, w_scale, out_scale, mult, shift)
LAYERS = [
    ("L1", 1 / 128, 1 / 512, 1 / 512, 16384, 21),
    ("L2", 1 / 512, 1 / 512, 1 / 1024, 16384, 22),
    ("L3", 1 / 1024, 1 / 512, 1 / 2048, 16384, 22),
    ("FC", 1 / 2048, 1 / 512, 1 / 4096, 16384, 22),
]


def qin_table() -> np.ndarray:
    """Exact (g-127.5)*256/255 rounded half-away-from-zero, clamped."""
    out = np.zeros(256, dtype=np.int64)
    for g in range(256):
        n = 256 * g - 32640
        q = (abs(n) + 127) // 255
        q = q if n >= 0 else -q
        out[g] = max(-128, min(127, q))
    return out


def make_inputs() -> dict[str, np.ndarray]:
    yy, xx = np.mgrid[0:48, 0:48]
    cases = {}
    # case0: upright silhouette (normal)
    img = np.full((48, 48), 32, dtype=np.uint8)
    body = ((xx - 24) ** 2 / 49.0 + (yy - 22) ** 2 / 196.0) <= 1.0
    img[body] = 190
    img[40:47, 18:30] = 150
    cases["case0_normal"] = img
    # case1: horizontal silhouette (fall)
    img = np.full((48, 48), 32, dtype=np.uint8)
    body = ((xx - 24) ** 2 / 400.0 + (yy - 30) ** 2 / 36.0) <= 1.0
    img[body] = 205
    cases["case1_fall"] = img
    # case2: textured blob + noise (other)
    rng = np.random.default_rng(SEED)
    img = np.full((48, 48), 24, dtype=np.uint8)
    img[(xx - 20) ** 2 + (yy - 20) ** 2 < 300] = 120
    img[(xx - 34) ** 2 + (yy - 34) ** 2 < 120] = 210
    img = np.clip(img.astype(np.int32) + rng.integers(-18, 19, size=(48, 48)), 0, 255).astype(np.uint8)
    cases["case2_other"] = img
    return cases


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    W.mkdir(parents=True, exist_ok=True)
    G.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)

    shapes = {"w1": 8 * 1 * 9, "w2": 16 * 8 * 9, "w3": 32 * 16 * 9, "w4": 3 * 32}
    weights = {k: rng.integers(-64, 64, size=n, dtype=np.int64) for k, n in shapes.items()}
    biases = {
        "b1": rng.integers(-600, 600, size=8, dtype=np.int64),
        "b2": rng.integers(-1500, 1500, size=16, dtype=np.int64),
        "b3": rng.integers(-2500, 2500, size=32, dtype=np.int64),
        "b4": rng.integers(-1200, 1200, size=3, dtype=np.int64),
    }
    mult = np.array([l[4] for l in LAYERS], dtype=np.int64)
    shift = np.array([l[5] for l in LAYERS], dtype=np.int64)
    qin = qin_table()

    write_hex(W / "qin.mem", qin, 8)
    for k, v in weights.items():
        write_hex(W / f"{k}.mem", v, 8)
    for k, v in biases.items():
        write_hex(W / f"{k}.mem", v, 32)
    # pad to 32 entries x 32 bit: Vivado did not accept the 4-entry memories as
    # $readmem targets ("invalid memory name"), a 32-deep ROM is unambiguous
    write_hex(W / "mult.mem", np.pad(mult, (0, 28), constant_values=0), 32)
    write_hex(W / "shift.mem", np.pad(shift, (0, 28), constant_values=0), 32)

    # RTL mirror of the quantisation parameters (single source of truth).
    # cnn_core.v includes this file; the .mem copies feed the Python reference.
    hdr = ["// generated by scripts/gen_model.py - do not edit"]
    for (nm, _si, _sw, _so, m, s) in LAYERS:
        hdr.append("localparam signed [15:0] M_%s = 16'sd%d;" % (nm, m))
        hdr.append("localparam [5:0] QS_%s = 6'd%d;" % (nm, s))
    (ROOT / "rtl" / "qparams.vh").write_text("\n".join(hdr) + "\n")

    files = {k: sha256(W / f"{k}.mem") for k in ["qin", "w1", "w2", "w3", "w4", "b1", "b2", "b3", "b4", "mult", "shift"]}
    manifest = {
        "class_order": CLASS_ORDER,
        "class_encoding": {"0": "normal", "1": "fall", "2": "other"},
        "layout": {
            "conv": "idx = (oc*IC + ic)*9 + (kh*3 + kw)",
            "fc": "idx = oc*32 + k",
            "mem_format": "one hex value per line, two's complement",
        },
        "layers": [
            {
                "name": name,
                "s_in": s_in,
                "s_w": s_w,
                "s_out": s_out,
                "mult": int(m),
                "shift": int(s),
            }
            for (name, s_in, s_w, s_out, m, s) in LAYERS
        ],
        "checkpoint_sha256": "N/A-structural-golden",
        "checkpoint_note": "weights are deterministic structural golden values, not a trained semantic checkpoint",
        "files": files,
        "file_lengths": {
            "qin": 256, "w1": 72, "b1": 8, "w2": 1152, "b2": 16, "w3": 4608,
            "b3": 32, "w4": 96, "b4": 3, "mult": 32, "shift": 32,
        },
        "input": {"size": 48, "quant": "q_in = round((g-127.5)*256/255) via qin.mem"},
    }
    (W / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (W / "SHA256SUMS.txt").write_text(
        "".join(f"{sha256(W / f'{k}.mem')}  {k}.mem\n" for k in files) +
        f"{sha256(W / 'manifest.json')}  manifest.json\n"
    )

    # golden vectors
    cases = make_inputs()
    cases["sat_pos"] = np.full((48, 48), 255, dtype=np.uint8)
    cases["sat_neg"] = np.zeros((48, 48), dtype=np.uint8)
    from int_reference import load_model
    model = load_model()
    summary = {}
    for name, img in cases.items():
        d = G / name
        d.mkdir(parents=True, exist_ok=True)
        write_hex(d / "roi.mem", img, 8)
        write_hex(d / "roi_q.mem", model["qin"][img.astype(np.int64)], 8)
        r = infer(img, model, dump=True)
        write_hex(d / "f1.mem", r["f1"].reshape(-1), 8)
        write_hex(d / "p1.mem", r["p1"].reshape(-1), 8)
        write_hex(d / "p2.mem", r["p2"].reshape(-1), 8)
        write_hex(d / "f2.mem", r["f2"].reshape(-1), 8)
        write_hex(d / "f3.mem", r["f3"].reshape(-1), 8)
        write_hex(d / "gap.mem", r["gap"].reshape(-1), 8)
        (d / "logits.txt").write_text(" ".join(str(int(v)) for v in r["logits"]) + "\n")
        summary[name] = {
            "logits": [int(v) for v in r["logits"]],
            "pred": int(r["pred"]),
            "logits_sha256": hashlib.sha256((d / "logits.txt").read_bytes()).hexdigest(),
        }
    (G / "golden_index.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
